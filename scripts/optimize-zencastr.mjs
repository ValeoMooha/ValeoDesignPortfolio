// Builds the optimised assets used by the Zencastr v2 page:
//  - responsive WebP versions of every image in public/works/zencastr-opt/
//  - re-encoded, silent, faststart MP4s plus a WebP poster per video
// and writes src/data/works-opt/zencastr.json (natural sizes + available widths).
// Run: node scripts/optimize-zencastr.mjs   (needs ffmpeg on PATH; safe to re-run)
import { readFileSync, writeFileSync, existsSync, mkdirSync, statSync, rmSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(root, 'public/works/zencastr');
const OUT = join(root, 'public/works/zencastr-opt');
const html = readFileSync(join(root, 'src/content/works/zencastr.html'), 'utf8');
const css = readFileSync(join(root, 'src/styles/works/d0e6c5b6.css'), 'utf8');

const rel = (m) => m.replace(/^.*works\/zencastr\//, '');
const imgs = new Map(); // rel path -> widths wanted
for (const m of html.matchAll(/<img[^>]*?src="([^"]+\.(?:jpg|png))"/g)) imgs.set(rel(m[1]), [640, 1280, 1920, 2560]);
for (const m of css.matchAll(/url\(([^)]*works\/zencastr\/[^)]+\.(?:jpg|png))\)/g)) {
  const p = rel(m[1]);
  if (!imgs.has(p)) imgs.set(p, [640, 1280]);
}
const videos = [...html.matchAll(/data-src="([^"]+\.(?:mp4|mov))"/g)].map((m) => rel(m[1]));

const stem = (p) => p.replace(/\.[^.]+$/, '');
const fresh = (out, src) => existsSync(out) && statSync(out).mtimeMs >= statSync(src).mtimeMs;
const manifest = { images: {}, videos: {} };

for (const [p, wanted] of imgs) {
  const src = join(SRC, p);
  const meta = await sharp(src).metadata();
  const widths = [...new Set(wanted.filter((w) => w < meta.width).concat(meta.width <= wanted.at(-1) ? [meta.width] : []))].sort((a, b) => a - b);
  if (!widths.length) widths.push(Math.min(meta.width, wanted.at(-1)));
  for (const w of widths) {
    const out = join(OUT, `${stem(p)}-${w}.webp`);
    if (fresh(out, src)) continue;
    mkdirSync(dirname(out), { recursive: true });
    await sharp(src).resize({ width: w, withoutEnlargement: true }).webp({ quality: 82, effort: 5 }).toFile(out);
  }
  manifest.images[p] = { w: meta.width, h: meta.height, widths };
}

for (const p of videos) {
  const src = join(SRC, p);
  const out = join(OUT, `${stem(p)}.mp4`);
  const poster = join(OUT, `${stem(p)}-poster.webp`);
  mkdirSync(dirname(out), { recursive: true });
  if (!fresh(out, src)) {
    execFileSync('ffmpeg', ['-y', '-v', 'error', '-i', src, '-an', '-vf', "scale='min(1600,iw)':-2,format=yuv420p",
      '-c:v', 'libx264', '-preset', 'slow', '-crf', '28', '-movflags', '+faststart', out]);
  }
  if (!fresh(poster, src)) {
    const tmp = join(OUT, `${stem(p)}-poster.png`);
    execFileSync('ffmpeg', ['-y', '-v', 'error', '-ss', '0.5', '-i', src, '-frames:v', '1', '-vf', "scale='min(1280,iw)':-2", tmp]);
    await sharp(tmp).webp({ quality: 78 }).toFile(poster);
    rmSync(tmp);
  }
  const meta = await sharp(poster).metadata();
  manifest.videos[p] = { w: meta.width, h: meta.height };
}

// Background images of the original CSS (phone mockups etc.) -> optimised WebP overrides.
const bg = [];
for (const m of css.matchAll(/\.zc (#brxe-[a-z]+) \{background-image: url\(([^)]*works\/zencastr\/[^)]+\.(?:jpg|png))\)/g)) {
  const p = rel(m[2]);
  const w = manifest.images[p].widths.filter((x) => x >= 1280)[0] ?? manifest.images[p].widths.at(-1);
  bg.push(`.zc.zc2 ${m[1]} { background-image: url(/works/zencastr-opt/${stem(p)}-${w}.webp) }`);
}
writeFileSync(join(root, 'src/styles/works/zencastr-v2-bg.css'), `/* generated by scripts/optimize-zencastr.mjs */\n${bg.join('\n')}\n`);

writeFileSync(join(root, 'src/data/works-opt/zencastr.json'), JSON.stringify(manifest, null, 1));
console.log(`${Object.keys(manifest.images).length} images, ${videos.length} videos`);
